def get_translator(language: Language) -> Callable[[str], str]:
    """Return a translation function for the specified language.

    Args:
        language: The language to translate to.

    Returns:
        A function that takes a key and returns the translated text.
    """
    translations = TRANSLATIONS.get(language, TRANSLATIONS[Language.ZH])

    def translate(key: str, *args, **kwargs) -> str:
        """Get translated text for a given key.

        Args:
            key: The translation key to look up.
            *args: Format arguments (deprecated, use .format() instead).
            **kwargs: Format keyword arguments for .format().

        Returns:
            The translated text, or the key itself if not found.
        """
        text = translations.get(key, key)
        if args or kwargs:
            return text.format(*args, **kwargs)
        return text

    return translate


def t(key: str, language: Language = Language.ZH, *args, **kwargs) -> str:
    """Convenience function to get translated text.

    Args:
        key: The translation key to look up.
        language: The language (defaults to Chinese).
        *args: Format arguments.
        **kwargs: Format keyword arguments.

    Returns:
        The translated text.
    """
    translator = get_translator(language)
    return translator(key, *args, **kwargs)
